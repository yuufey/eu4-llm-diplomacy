#include "../information-battle-drain.h"
#include "../information-battle-log-writer.h"

#include <array>
#include <atomic>
#include <cstddef>
#include <cstdint>
#include <cstdlib>
#include <iostream>
#include <string_view>

namespace information_battle_source {

namespace battle = information::battle;

constexpr battle::Identity kIdentity{0x1111222233334444ULL, 0x307ULL};

// These are the source-state names used by the production helper.  Keeping
// the fixture's state surface identical lets the runner compile the exact
// helper text extracted from information-battle-observer.inc.
constexpr long enabled = 1;
constexpr long fault = 3;
std::atomic<long> state{enabled};
battle::OwnedBattleDrain drain(kIdentity);

struct FakeWriter final {
    battle::LogStatus current_status = battle::LogStatus::ready;
    battle::LogStatus rejection_status = battle::LogStatus::write_failed;
    std::size_t busy_rejections_remaining = 0;
    bool accept_after_rejection = true;
    bool latched = false;
    std::array<std::uint64_t, 16> attempted_sequences{};
    std::array<std::uint64_t, 16> written_sequences{};
    std::size_t attempt_count = 0;
    std::size_t write_count = 0;

    bool operator()(const battle::Record& record) noexcept {
        if (attempt_count < attempted_sequences.size()) {
            attempted_sequences[attempt_count] = record.attempt_sequence;
        }
        ++attempt_count;

        if (busy_rejections_remaining != 0) {
            --busy_rejections_remaining;
            current_status = battle::LogStatus::lock_busy;
            return false;
        }
        if (!accept_after_rejection) {
            current_status = rejection_status;
            return false;
        }

        current_status = battle::LogStatus::ready;
        if (write_count < written_sequences.size()) {
            written_sequences[write_count] = record.attempt_sequence;
        }
        ++write_count;
        return true;
    }

    battle::LogStatus status() const noexcept { return current_status; }
    bool fault_latched() const noexcept { return latched; }
};

FakeWriter writer;

// This file is generated by the owned runner from the exact production
// static helper.  It is intentionally included after the fixture globals.
#include "production-drain-fragments.inc"

namespace {

void require(bool condition, const char* message) {
    if (!condition) {
        std::cerr << "FAIL: " << message << '\n';
        std::abort();
    }
}

void push_records(std::size_t count) {
    for (std::size_t index = 0; index < count; ++index) {
        const std::array<std::uint8_t, 3> payload{
            {static_cast<std::uint8_t>(0x20U + index), 0x5aU, 0xa5U}};
        const auto pushed = drain.push(kIdentity, payload.data(), payload.size());
        require(pushed.accepted(), "fixture record is accepted");
        require(pushed.attempt_sequence == index + 1,
                "fixture record receives the expected initial sequence");
    }
}

void require_enabled_and_pending(const char* context) {
    (void)context;
    require(state.load(std::memory_order_acquire) == enabled,
            "lock contention does not latch source fault");
    require(drain.has_pending(), "rejected fragment remains pending");
}

void test_one_lock_busy_then_success() {
    push_records(2);
    writer.busy_rejections_remaining = 1;

    require(!drain_fragments(), "first lock-busy drain is deferred");
    require_enabled_and_pending("one-lock-busy");
    require(writer.attempt_count == 1 && writer.write_count == 0,
            "first lock-busy attempt writes no acknowledged record");
    require(writer.attempted_sequences[0] == 1,
            "first rejected record has sequence one");

    require(drain_fragments(), "retry succeeds after lock is available");
    require(state.load(std::memory_order_acquire) == enabled,
            "successful retry leaves source enabled");
    require(!drain.has_pending(), "successful retry clears all pending work");
    require(writer.attempt_count == 3 && writer.write_count == 2,
            "retry writes each queued record exactly once after success");
    require(writer.attempted_sequences[1] == 1
                && writer.attempted_sequences[2] == 2,
            "retry preserves the first sequence and then publishes the next");
    require(writer.written_sequences[0] == 1
                && writer.written_sequences[1] == 2,
            "successful records are acknowledged in FIFO order");
    require(drain.stats().last_attempt_sequence == 2,
            "lock-busy retry does not allocate an early new sequence");
}

void test_multiple_lock_busy_retries() {
    push_records(1);
    writer.busy_rejections_remaining = 2;

    require(!drain_fragments(), "first repeated lock-busy drain is deferred");
    require_enabled_and_pending("multiple-lock-busy-first");
    require(!drain_fragments(), "second repeated lock-busy drain is deferred");
    require_enabled_and_pending("multiple-lock-busy-second");
    require(writer.attempt_count == 2 && writer.write_count == 0
                && writer.attempted_sequences[0] == 1
                && writer.attempted_sequences[1] == 1,
            "repeated lock-busy attempts retain one exact sequence");

    require(drain_fragments(), "record eventually succeeds after repeated busy");
    require(state.load(std::memory_order_acquire) == enabled
                && !drain.has_pending(),
            "eventual success clears pending without a fault");
    require(writer.attempt_count == 3 && writer.write_count == 1
                && writer.written_sequences[0] == 1,
            "eventual success writes the pending record exactly once");
}

void test_non_busy_rejection_fault(battle::LogStatus status_value) {
    push_records(1);
    writer.accept_after_rejection = false;
    writer.rejection_status = status_value;

    require(!drain_fragments(), "non-busy sink rejection returns false");
    require(state.load(std::memory_order_acquire) == fault,
            "non-busy sink rejection latches source fault");
    require(drain.has_pending(), "fault does not silently discard rejected work");
    require(writer.attempt_count == 1 && writer.write_count == 0,
            "faulting rejection has one failed attempt and no write");
}

void test_latched_busy_fault() {
    push_records(1);
    writer.busy_rejections_remaining = 1;
    writer.latched = true;

    require(!drain_fragments(), "latched lock-busy returns false");
    require(state.load(std::memory_order_acquire) == fault,
            "latched lock-busy cannot use the retry exception");
    require(drain.has_pending(), "latched busy still retains rejected work");
}

void test_latched_success_fault() {
    push_records(1);
    writer.latched = true;

    require(!drain_fragments(), "latched writer returns false from helper");
    require(state.load(std::memory_order_acquire) == fault,
            "a latched writer faults even when sink delivery returns true");
    require(!drain.has_pending() && writer.write_count == 1,
            "latched-success case does not duplicate the already delivered record");
}

} // namespace
} // namespace information_battle_source

int main(int argc, char** argv) {
    using namespace information_battle_source;
    if (argc != 2) {
        std::cerr << "usage: information-battle-fragment-retry-test <case>\n";
        return 2;
    }

    const std::string_view selected(argv[1]);
    if (selected == "busy-once") {
        test_one_lock_busy_then_success();
    } else if (selected == "busy-multiple") {
        test_multiple_lock_busy_retries();
    } else if (selected == "fault-identity") {
        test_non_busy_rejection_fault(battle::LogStatus::identity_mismatch);
    } else if (selected == "fault-encode") {
        test_non_busy_rejection_fault(battle::LogStatus::encode_failed);
    } else if (selected == "fault-write") {
        test_non_busy_rejection_fault(battle::LogStatus::write_failed);
    } else if (selected == "fault-flush") {
        test_non_busy_rejection_fault(battle::LogStatus::flush_failed);
    } else if (selected == "fault-rollback") {
        test_non_busy_rejection_fault(battle::LogStatus::rollback_fault);
    } else if (selected == "latched-busy") {
        test_latched_busy_fault();
    } else if (selected == "latched-success") {
        test_latched_success_fault();
    } else {
        std::cerr << "unknown case: " << argv[1] << '\n';
        return 2;
    }

    std::cout << "PASS information-battle-fragment-retry " << selected << '\n';
    return 0;
}
