template<class Reader>
bool guard(Reader& reader,Address base,std::size_t image_size) noexcept {
    constexpr Address address_limit=UINT64_C(0x800000000000);
    if (base<0x10000u || base>=address_limit || image_size!=kSizeOfImage
        || image_size>address_limit-base
        || kNativeGuardRva+kNativeGuardSpanBytes>image_size
        || kPdataRowRva+kPdataRowBytes.size()>image_size
        || kUnwindInfoRva+kUnwindInfoSpanBytes>image_size) return false;

    std::array<unsigned char,kNativeGuardSpanBytes> code{};
    std::array<unsigned char,kPdataRowBytes.size()> pdata{};
    std::array<unsigned char,kUnwindInfoSpanBytes> unwind{};
    if (!reader.read(base+kNativeGuardRva,code.data(),code.size())
        || !reader.read(base+kPdataRowRva,pdata.data(),pdata.size())
        || !reader.read(base+kUnwindInfoRva,unwind.data(),unwind.size())) return false;
    return code==kNativeGuardBytes && pdata==kPdataRowBytes && unwind==kUnwindInfoBytes;
}

