template<class Reader> bool guard(Reader& reader,Address base,std::size_t image_size,
                                  Address plugin_base=0, std::size_t plugin_size=0) noexcept {
    constexpr Address limit=UINT64_C(0x800000000000);
    if (base<0x10000u || image_size>512u*1024u*1024u || !image_size
        || base>=limit || image_size>limit-base
        || kGlobalStringRva+32u>image_size
        || kHelperRva+kHelperBytes.size()>image_size
        || kDestructorRva+kDestructorBytes.size()>image_size) return false;
    const bool has_plugin=plugin_base!=0 || plugin_size!=0;
    if (has_plugin) {
        if (!plugin_base || plugin_size!=kPluginSize
            || plugin_base<0x10000u || plugin_base>=limit
            || plugin_size>limit-plugin_base
            || kPluginBridgeRva+kPluginBridgeBytes.size()>plugin_size
            || kPluginHelperRva+kPluginHelperBytes.size()>plugin_size
            || kPluginUnwindRva+kPluginUnwindBytes.size()>plugin_size
            || kPluginCallSlotRva+sizeof(Address)>plugin_size
            || kPluginReturnSlotRva+sizeof(Address)>plugin_size) return false;
    }
    std::array<unsigned char,kHelperBytes.size()> helper{};
    std::array<unsigned char,kDestructorBytes.size()> destructor{};
    if (!reader.read(base+kHelperRva,helper.data(),helper.size())
        || !reader.read(base+kDestructorRva,destructor.data(),destructor.size())
        || destructor!=kDestructorBytes) return false;
    if (!has_plugin) return helper==kHelperBytes;
    std::array<unsigned char,kPluginBridgeBytes.size()> bridge{};
    std::array<unsigned char,kPluginHelperBytes.size()> plugin_helper{};
    std::array<unsigned char,kPluginUnwindBytes.size()> unwind{};
    Address call_slot=0;
    Address return_slot=0;
    if (!reader.read(plugin_base+kPluginBridgeRva,bridge.data(),bridge.size())
        || bridge!=kPluginBridgeBytes
        || !reader.read(plugin_base+kPluginHelperRva,plugin_helper.data(),plugin_helper.size())
        || plugin_helper!=kPluginHelperBytes
        || !reader.read(plugin_base+kPluginUnwindRva,unwind.data(),unwind.size())
        || unwind!=kPluginUnwindBytes
        || !reader.read(plugin_base+kPluginCallSlotRva,
                        reinterpret_cast<unsigned char*>(&call_slot),sizeof(call_slot))
        || !reader.read(plugin_base+kPluginReturnSlotRva,
                        reinterpret_cast<unsigned char*>(&return_slot),sizeof(return_slot))
        || call_slot!=plugin_base+kPluginHelperRva
        || return_slot!=base+kPluginReturnGameRva) return false;
    for (std::size_t i=0;i<helper.size();++i) {
        if (i>=kHelperPluginPatchOffset
            && i<kHelperPluginPatchOffset+kHelperPluginPatchBytes) continue;
        if (helper[i]!=kHelperBytes[i]) return false;
    }
    std::array<unsigned char,kHelperPluginPatchBytes> expected_patch{};
    expected_patch[0]=0xffu; expected_patch[1]=0x25u;
    const Address target=plugin_base+kPluginTargetRva;
    std::memcpy(expected_patch.data()+6u,&target,sizeof(target));
    for (std::size_t i=0;i<expected_patch.size();++i)
        if (helper[kHelperPluginPatchOffset+i]!=expected_patch[i]) return false;
    return true;
}

